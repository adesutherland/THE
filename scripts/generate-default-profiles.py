#!/usr/bin/env python3
"""Generate matched cREXX and Regina defaults from one command/theme definition."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def generated():
    data = json.loads((ROOT / 'profiles/default-profile.json').read_text())
    result = {}
    for engine, filename, suffix in [('CREXX', 'profile.the', ''), ('REGINA', 'profile_regina.the', '_regina')]:
        header = '/* Generated by scripts/generate-default-profiles.py; edit profiles/default-profile.json. */\n'
        if engine == 'CREXX':
            header += 'options levelb\nimport rxfnsb\n'
        lines = [header, 'address the']
        for command in data['commands']:
            lines.append(quote(command.format(suffix=suffix)) + ';')
        if engine == 'CREXX':
            lines += ['version = .string[]', 'address the "extract /version/" expose version[]', 'platform = version[3]',
                      'size = .string[]','address the "extract /size/" expose size[]',
                      "if size[1] > 0 then 'cursor goto 1 1';", "else 'bottom';"]
        else:
            lines += [quote('extract /version/'), 'platform = version.3',quote('extract /size/'),
                      "if size.1 > 0 then 'cursor goto 1 1';", "else 'bottom';"]
        lines += ["check = 'osquiet command -v '", "discard = ' 2>/dev/null'",
                  "if left(platform,3) = 'WIN' then do", "  check = 'osquiet where.exe '",
                  "  discard = ' 2>nul'", 'end']
        for parser in data['parsers']:
            lines += ["address the check || '" + parser['program'] + "' || discard;", 'if rc = 0 then do',
                      '  ' + quote('set sdslh ' + parser['name'] + ' ' + parser['program'] + ' ' + parser['arguments']) + ';']
            for mask in parser['masks']:
                lines.append('  ' + quote('set autocolor ' + mask + ' ' + parser['name']) + ';')
            lines.append('end')
        # Windows PDCurses has editor block clipboard support. On macOS/Linux
        # retain terminal clipboard shortcuts rather than bind unsupported APIs.
        lines += ["if left(platform,3) = 'WIN' then do", "  'define c-c clipboard copy';",
                  "  'define c-x clipboard cut';", "  'define c-v clipboard paste';", 'end',
                  quote(data['welcome']) + ';']
        result[filename] = '\n'.join(lines) + '\n'
        restricted = [quote(command) + ';' for command in
                      ['set impos off','set impmacro off','set macro off','set linend off','set synonym off']]
        web_name = 'web-profile.the' if engine == 'CREXX' else 'web-profile-regina.the'
        result[web_name] = '\n'.join(lines[:-1] + restricted +
                                    [quote('msg CRXTHE 0.9.0 | Esc Command  F6 Cmd/File  F1 Help  Ctrl-S Save') + ';']) + '\n'
        for name, prompt in [('quickfind', 'locate /'), ('quickopen', 'edit '), ('quickline', ':')]:
            body = ('options levelb\n' if engine == 'CREXX' else '') + 'address the\n'
            body += quote('cmsg ' + prompt) + ';\n' + quote('cursor cmdline ' + str(len(prompt) + 1)) + ';\n'
            result[name + suffix + '.the'] = body
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(name + ': regenerate default profiles')
        else:
            path.write_text(text)
    print('Matched cREXX/Regina defaults ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
