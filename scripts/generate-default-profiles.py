#!/usr/bin/env python3
"""Generate matched cREXX and Regina defaults from one command/theme definition."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def quote(text):
    return "'" + text.replace("'", "''") + "'"


def generated():
    data = json.loads((ROOT / 'profiles/default-profile.json').read_text())
    result = {}
    for engine, filename, suffix in [('CREXX', 'profile.the', ''), ('REGINA', 'profile_regina.the', '_regina')]:
        header = '/* Generated by scripts/generate-default-profiles.py; edit profiles/default-profile.json. */\n'
        if engine == 'CREXX':
            header += 'options levelb\nimport rxfnsb\n'
        lines = [header, 'address the']
        for command in data['commands']:
            lines.append(quote(command.format(suffix=suffix)) + ';')
        if engine == 'CREXX':
            lines += ['version = .string[]', 'address the "extract /version/" expose version[]', 'platform = version[3]',
                      'size = .string[]','address the "extract /size/" expose size[]',
                      "if size[1] > 0 then 'cursor goto 1 1';", "else 'bottom';"]
        else:
            lines += [quote('extract /version/'), 'platform = version.3',quote('extract /size/'),
                      "if size.1 > 0 then 'cursor goto 1 1';", "else 'bottom';"]
        # Unix DEL is the Backspace byte (127); forward Delete is curses DC.
        # PDCurses instead names its forward Delete key DEL.
        lines += ["if left(platform,3) = 'WIN' then 'define del sos cuadelchar';",
                  "if left(platform,3) \\= 'WIN' then 'define dc sos cuadelchar';"]
        lines += ["check = 'osquiet command -v '", "discard = ' 2>/dev/null'",
                  "if left(platform,3) = 'WIN' then do", "  check = 'osquiet where.exe '",
                  "  discard = ' 2>nul'", 'end']
        for parser in data['parsers']:
            lines += ["address the check || '" + parser['program'] + "' || discard;", 'if rc = 0 then do',
                      '  ' + quote('set sdslh ' + parser['name'] + ' ' + parser['program'] + ' ' + parser['arguments']) + ';']
            for mask in parser['masks']:
                lines.append('  ' + quote('set autocolor ' + mask + ' ' + parser['name']) + ';')
            lines.append('end')
        # Windows PDCurses has editor block clipboard support. On macOS/Linux
        # retain terminal clipboard shortcuts rather than bind unsupported APIs.
        lines += ["if left(platform,3) = 'WIN' then do", "  'define c-c clipboard copy';",
                  "  'define c-x clipboard cut';", "  'define c-v clipboard paste';", 'end']
        # Shared session definitions are data. A successful profile activation
        # publishes this graph; declaring it never invokes the commands.
        workbench = ['workbench begin owner profile.default',
                     'workbench reset owner profile.default']
        placements = {}
        for group in data['native_menu_groups']:
            workbench.append('workbench menu put ' + group['id'] + ' label "' +
                             group['label'] + '" order ' + str(group['order']))
            for index in group['entries']:
                if index in placements or not 1 <= index <= len(data['native_menu']):
                    raise ValueError('native_menu_groups contains an invalid or repeated entry')
                placements[index] = group['id']
        for index, (label, command) in enumerate(data.get('native_menu', []), 1):
            action = 'profile.action.' + str(index)
            item = 'profile.item.' + str(index)
            escaped_label = label.replace('"', '""')
            escaped_command = command.format(suffix=suffix).replace('"', '""')
            builtin = {'save': 'file.save', 'quit': 'file.close', 'sos undo': 'edit.undo'}.get(command)
            invocation = ('builtin ' + builtin) if builtin else ('command "' + escaped_command + '"')
            # Keep legacy IDs callable without duplicating builtin File/Edit
            # rows or exposing profile administration beside every file.
            workbench.append('workbench action put ' + action + ' label "' + escaped_label +
                             '" ' + invocation)
            if index in placements:
                # Stock extensions follow the builtin File/Edit operations
                # when a graphical host merges their shared menu groups.
                workbench.append('workbench item put ' + placements[index] + ' ' + item + ' label "' +
                                 escaped_label + '" action ' + action + ' order ' + str(100 + index))
        workbench += ['workbench commit']
        shared_lines = [quote(command) + ';' for command in workbench]
        native = [quote(command.format(suffix=suffix)) + ';'
                  for command in data.get('native_commands', [])]
        # UI describes the active runtime driver. Keep GTK's editing binding;
        # only a terminal curses driver implements native chrome navigation.
        if engine == 'CREXX':
            native += ['ui = .string[]', 'address the "extract /ui/" expose ui[]',
                       "if pos('CURSES', translate(ui[1])) > 0 then do"]
        else:
            native += [quote('extract /ui/'),
                       "if pos('CURSES', translate(ui.1)) > 0 then do"]
        native += ['  ' + quote(command.format(suffix=suffix)) + ';'
                   for command in data.get('curses_commands', [])] + ['end']
        result[filename] = '\n'.join(lines + shared_lines + native) + '\n'
        restricted = [quote(command) + ';' for command in
                      ['set impos off','set impmacro off','set macro off','set linend off','set synonym on']]
        web = [quote(command.format(suffix=suffix)) + ';'
               for command in data.get('web_commands', [])]
        web_name = 'web-profile.the' if engine == 'CREXX' else 'web-profile-regina.the'
        result[web_name] = '\n'.join(lines + web + restricted) + '\n'
        for name, prompt in [('quickfind', 'locate /'), ('quickopen', 'edit '), ('quickline', ':')]:
            body = ('options levelb\n' if engine == 'CREXX' else '') + 'address the\n'
            body += quote('cmsg ' + prompt) + ';\n' + quote('cursor cmdline ' + str(len(prompt) + 1)) + ';\n'
            result[name + suffix + '.the'] = body
        menu = data.get('native_menu', [])
        if any('/' in label for label, _ in menu):
            raise ValueError('native_menu labels must not contain the POPUP delimiter /')
        menu_command = 'popup topleft escape esc /' + '/'.join(item[0] for item in menu)
        body = '/* Generated native command menu; edit profiles/default-profile.json. */\n'
        body += ('options levelb\n' if engine == 'CREXX' else '') + 'address the\n'
        if engine == 'CREXX':
            body += 'popup = .string[]\naddress the ' + quote(menu_command) + ' expose popup[];\n'
            choice = 'popup[2]'
        else:
            body += quote(menu_command) + ';\n'
            choice = 'popup.2'
        body += 'select\n'
        for index, (_, command) in enumerate(menu, 1):
            body += '  when ' + choice + ' = ' + str(index) + ' then ' + quote(command.format(suffix=suffix)) + ';\n'
        body += '  otherwise nop\nend\n'
        result['workbenchmenu' + suffix + '.the'] = body
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(name + ': regenerate default profiles')
        else:
            path.write_text(text)
    print('Matched cREXX/Regina defaults ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
